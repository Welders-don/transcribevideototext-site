  var RTL = { ar: true };

  function pick() {
    var langs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || 'en'];
    for (var i = 0; i < langs.length; i++) {
      var code = String(langs[i]).toLowerCase().split('-')[0];
      if (DICT[code]) return code;
    }
    return 'en';
  }

  var LANG = pick();
  var TABLE = DICT[LANG];

  function t(key, subs) {
    var s = (TABLE && TABLE[key]) || DICT.en[key] || key;
    if (subs) {
      for (var k in subs) s = s.replace('{' + k + '}', subs[k]);
    }
    return s;
  }

  // Разметка: data-i18n подставляет текст, data-i18n-html — там, где внутри <b>
  function apply(root) {
    (root || document).querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = t(el.dataset.i18n);
    });
    (root || document).querySelectorAll('[data-i18n-html]').forEach(function (el) {
      el.innerHTML = t(el.dataset.i18nHtml); // только наши собственные строки, не данные юзера
    });
  }

  document.documentElement.lang = LANG;
  if (RTL[LANG]) document.documentElement.dir = 'rtl';

  window.I18N = { t: t, apply: apply, lang: LANG, langs: Object.keys(DICT) };
